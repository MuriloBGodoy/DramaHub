-- DramaHub: catalogo publico + dados por navegador (login anonimo do Supabase).

create table public.series (
  id          bigint generated by default as identity primary key,
  title       text not null,
  synopsis    text,
  cover_url   text,
  genre       text,
  tags        text,            -- separadas por virgula, ex: "romance,ceo,vinganca"
  source      text,            -- "yt" (canal oficial) ou "ai" (drama gerado por IA)
  credit      text,
  featured    boolean not null default false,
  script      text,            -- roteiro do Roteirista IA (JSON)
  created_at  timestamptz not null default now()
);
create index series_featured_created on public.series (featured desc, created_at desc);

create table public.episode (
  id             bigint generated by default as identity primary key,
  series_id      bigint not null references public.series on delete cascade,
  number         int not null,
  title          text,
  video_url      text,
  youtube_id     text,
  thumbnail_url  text,
  start_sec      double precision,
  end_sec        double precision,
  duration_sec   int,
  unique (series_id, number)
);
create index episode_youtube_id on public.episode (youtube_id);

-- Um perfil por usuario anonimo (= um navegador)
create table public.profile (
  id          uuid primary key references auth.users on delete cascade,
  name        text not null default 'Visitante',
  avatar      text not null default '🍿',
  is_admin    boolean not null default false,
  created_at  timestamptz not null default now()
);

create table public.watch_progress (
  user_id       uuid not null default auth.uid() references auth.users on delete cascade,
  episode_id    bigint not null references public.episode on delete cascade,
  position_sec  double precision not null default 0,
  completed     boolean not null default false,
  updated_at    timestamptz not null default now(),
  primary key (user_id, episode_id)
);

create table public.favorite (
  user_id     uuid not null default auth.uid() references auth.users on delete cascade,
  series_id   bigint not null references public.series on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, series_id)
);

-- Segredos do app (ex: admin_code). RLS sem policies: so funcoes security definer leem.
create table public.app_secret (
  key    text primary key,
  value  text not null
);

-- ---------- funcoes ----------

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce((select is_admin from public.profile where id = auth.uid()), false)
$$;

-- Libera o Estudio para o navegador atual
create function public.unlock_admin(code text) returns public.profile
language plpgsql security definer set search_path = '' as $$
declare p public.profile;
begin
  if auth.uid() is null then raise exception 'Sem sessao'; end if;
  if not exists (select 1 from public.app_secret where key = 'admin_code' and value = code) then
    raise exception 'Código incorreto';
  end if;
  update public.profile set is_admin = true where id = auth.uid() returning * into p;
  return p;
end $$;

-- "Começar do zero": apaga o usuario anonimo (progresso/favoritos/perfil vao junto)
create function public.delete_me() returns void
language sql security definer set search_path = '' as $$
  delete from auth.users where id = auth.uid() and is_anonymous
$$;

-- Perfil criado junto com o usuario
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profile (id) values (new.id) on conflict do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create view public.genres with (security_invoker = true) as
  select distinct genre from public.series where genre is not null order by genre;

-- ---------- RLS ----------

alter table public.series enable row level security;
alter table public.episode enable row level security;
alter table public.profile enable row level security;
alter table public.watch_progress enable row level security;
alter table public.favorite enable row level security;
alter table public.app_secret enable row level security;

create policy "catalogo publico" on public.series for select using (true);
create policy "admin cria serie" on public.series for insert to authenticated with check (public.is_admin());
create policy "admin edita serie" on public.series for update to authenticated using (public.is_admin());
create policy "admin apaga serie" on public.series for delete to authenticated using (public.is_admin());

create policy "episodios publicos" on public.episode for select using (true);
create policy "admin cria episodio" on public.episode for insert to authenticated with check (public.is_admin());
create policy "admin edita episodio" on public.episode for update to authenticated using (public.is_admin());
create policy "admin apaga episodio" on public.episode for delete to authenticated using (public.is_admin());

create policy "meu perfil" on public.profile for select to authenticated using (id = auth.uid());
create policy "edito meu perfil" on public.profile for update to authenticated using (id = auth.uid());
-- is_admin so muda via unlock_admin()
revoke update on public.profile from anon, authenticated;
grant update (name, avatar) on public.profile to authenticated;

create policy "meu progresso" on public.watch_progress for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "meus favoritos" on public.favorite for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

revoke execute on function public.unlock_admin(text), public.delete_me() from anon, public;
